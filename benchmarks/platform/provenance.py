"""Oracle provenance (HARNESS.md "Custody and reuse"; control 9).

An oracle is admissible only when its producing run is identifiable:
producer interpreter, reference wheel/source digests, profile, run ID and
harness version.  A stored file whose metadata is absent (filename-only
reuse) or whose producer IS the candidate fails closed.
"""
from __future__ import annotations

from .errors import ProvenanceError

REQUIRED_FIELDS = ("producer_python", "reference_wheel_sha256",
                   "reference_source_sha256", "profile", "run_id",
                   "harness_version")


def check_oracle_provenance(oracle_meta: dict, candidate_identity: dict,
                            reference_expected: dict) -> None:
    """Fail unless the oracle metadata proves an independent reference run.

    oracle_meta: metadata carried beside the oracle outputs.
    candidate_identity: resolved identity of the system under test.
    reference_expected: frozen reference digests from the contract
        (e.g. the una_legacy wheel tree sha256).
    """
    if not isinstance(oracle_meta, dict) or not oracle_meta:
        raise ProvenanceError(
            "oracle metadata absent: filename-only reuse is not provenance "
            "(control 9)")
    missing = [f for f in REQUIRED_FIELDS if not oracle_meta.get(f)]
    if missing:
        raise ProvenanceError(f"oracle metadata missing fields: {missing}")
    if reference_expected.get("wheel_tree_sha256") and \
            oracle_meta["reference_wheel_sha256"] != \
            reference_expected["wheel_tree_sha256"]:
        raise ProvenanceError(
            "oracle was produced by a different reference build than the "
            f"frozen contract ({oracle_meta['reference_wheel_sha256'][:12]} "
            f"!= {reference_expected['wheel_tree_sha256'][:12]})")
    cand_wheel = candidate_identity.get("installed_tree_sha256")
    if cand_wheel and \
            oracle_meta["reference_wheel_sha256"] == cand_wheel and \
            oracle_meta.get("producer_run_equals_candidate", False):
        raise ProvenanceError(
            "oracle was generated by the candidate itself (same installed "
            "tree, same run); control 9")
    # same-tree + same-run-id recorded by the harness is the self-oracle tell
    if cand_wheel and \
            oracle_meta["reference_wheel_sha256"] == cand_wheel and \
            candidate_identity.get("module_file") and \
            oracle_meta.get("producer_module_file") and \
            oracle_meta["producer_module_file"] == \
            candidate_identity["module_file"] and \
            oracle_meta.get("profile") == candidate_identity.get("profile"):
        raise ProvenanceError(
            "oracle produced by the candidate process (identical module "
            "file and profile); control 9")


def oracle_metadata_from_run(record: dict) -> dict:
    """Build oracle metadata from a completed reference-run record."""
    ident = record.get("child_identity") or {}
    return {
        "producer_python": ident.get("python"),
        "reference_wheel_sha256": ident.get("installed_tree_sha256"),
        "reference_source_sha256": record.get("reference_source_sha256"),
        "profile": record.get("profile"),
        "run_id": record.get("run_id"),
        "harness_version": record.get("harness_version"),
        "producer_module_file": ident.get("module_file"),
        "outputs": record.get("outputs"),
    }
